let lang = 'es';
try { lang = JSON.parse(localStorage.getItem('lang')) || (navigator.language?.startsWith('en') ? 'en' : 'es'); } catch { /* default */ }
if (!DICT[lang]) lang = 'es';

function t(key, vars) {
  let s = DICT[lang][key] ?? DICT.es[key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll(`{{${k}}}`, vars[k]);
  return s;
}

function getLang() { return lang; }

function setLang(next) {
  if (!DICT[next]) return;
  lang = next;
  try { localStorage.setItem('lang', JSON.stringify(lang)); } catch { /* sin espacio */ }
  document.documentElement.setAttribute('lang', lang);
  applyStaticI18n();
  if (typeof onLangChange === 'function') onLangChange(lang);
}

// Recorre el DOM aplicando data-i18n / data-i18n-placeholder / data-i18n-title
// a los textos que no cambian dinámicamente por JS.
function applyStaticI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.getAttribute('data-i18n')); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.getAttribute('data-i18n-placeholder')); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.getAttribute('data-i18n-title')); });
}
